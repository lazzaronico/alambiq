"""How completion proposals appear in the dossier."""

from __future__ import annotations

from alambiq.report.page import esc, table


def render(result) -> str:
    rows = [
        [
            p.id,
            p.seed,
            p.status,
            ", ".join(f"{m.before}{m.position}{m.after}" for m in p.mutations)
            or ("none" if p.status == "completed" else ""),
            p.duplicate_of or "",
            p.reason or "",
        ]
        for p in result.proposals
    ]
    return "".join(
        [
            f"<p>{result.accepted} of {len(result.proposals)} proposals accepted for "
            f"{esc(result.protein_id)} ({result.length} residues, {result.masked} masked), "
            f"generated by {esc(result.model)} on {esc(result.device)}.</p>",
            f"<pre>{esc(result.prompt)}</pre>",
            table(
                ["Proposal", "Seed", "Status", "Changes", "Duplicate of", "Reason"],
                rows,
                numeric={1},
            ),
        ]
    )
